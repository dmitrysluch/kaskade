/**
 * Обучающий слой (07-оболочка-тз, «Обучающий слой»).
 *
 * Отдельный от терминала слой поверх него: другая типографика, вне сетки. Это
 * инструкция к игре, а не игра, и притворяться диегетичной ей не надо —
 * притворство тут хуже прямоты.
 *
 * Экран управления показывается один раз, перед первой комнатой, и дальше живёт
 * клавишей F3: модалка, исчезнувшая навсегда, — не обучение, первый же
 * отвлёкшийся игрок останется без неё. Командой `управление` он не открывается
 * намеренно — метаинструкция не притворяется действием терминала.
 */

import { ADVANCE_LEGEND, ADVANCE_MARK } from './lines.ts';

const KEYS: [string, string][] = [
  ['↑ ↓', 'выбрать'],
  ['Tab', 'дополнить'],
  ['Enter', 'выполнить'],
  ['Esc', 'очистить ввод'],
  ['F1', 'справочник'],
  ['F2', 'дело — слова, которые вы узнали'],
  ['F3', 'управление'],
  ['F10', 'меню — начать заново'],
];

export function Manual({ first }: { first: boolean }) {
  return (
    <div className="manual">
      <div className="manual-box">
        <p className="manual-lead">Игра управляется с клавиатуры. Мыши нет.</p>
        <p>
          Выбирайте команду стрелками или начинайте печатать — строка ввода отфильтрует всё, что
          сейчас можно сделать.
        </p>

        <dl className="manual-keys">
          {KEYS.map(([key, what]) => (
            <div key={key}>
              <dt>{key}</dt>
              <dd>{what}</dd>
            </div>
          ))}
        </dl>

        {/* Та же легенда, что под выбранной командой: игрок не обязан ловить её
            в автокомплите, чтобы узнать, что значит треугольник. */}
        <p className="manual-advance">
          <span className="advance">{ADVANCE_MARK}</span> {ADVANCE_LEGEND}
        </p>

        <p className="manual-go">любая клавиша — {first ? 'начать' : 'закрыть'}</p>
      </div>
    </div>
  );
}

/**
 * Подсказка-пример — параллельно, а не вместо. Висит поверх терминала в первой
 * комнате и уходит после третьей команды; собственная строка подсказок терминала
 * при этом не меняется никогда.
 *
 * Соблазн подменить её примером надо давить: игрок привыкнет к временному
 * интерфейсу, а потом тот поменяется под ним.
 */
export function Hint({ text }: { text: string }) {
  return <div className="hint">попробуйте: {text}</div>;
}
