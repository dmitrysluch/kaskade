/**
 * Страницы предмета (07-оболочка-тз, «Страницы предмета — состояния»).
 *
 * Многостраничная вещь — учебник, папка, инструкция — остаётся одним предметом:
 * страницы это обычные секции того же файла с `- page: N`. Заголовок секции
 * хранит состояние и попадает в сейв, число задаёт только порядок — поэтому
 * номер можно переставить, не ломая сохранение.
 *
 * Здесь лежат те несколько слов, которые движок произносит сам. Их приходится
 * зашивать в код по той же причине, по которой зашиты служебные команды:
 * `осмотреть` и `листать` не объявлены ни в одной заметке, их создаёт оболочка.
 */

/** Глагол, на который отвечают страницы. Он же дефолтный генератор комнаты. */
export const EXAMINE = 'осмотреть';

export const LEAF = 'листать';

/** `листать учебник вперёд` — метку строит движок, в контенте её нет. */
export function leafLabel(item: string, forward: boolean): string {
  return `${LEAF} ${item} ${forward ? 'вперёд' : 'назад'}`;
}
